// Build: the knowledge-base bundle (in the ns-ingredients submodule), the self-hosted fonts, then the Worker bundle.
// deno task build
const run = async (args: string[], cwd?: string) => {
  const { code } = await new Deno.Command("deno", { args, cwd, stdout: "inherit", stderr: "inherit" })
    .output();
  if (code !== 0) throw new Error(`deno ${args.join(" ")} exited ${code}`);
};

await run(
  ["run", "--allow-read", "--allow-write=dist", "scripts/build-kb-bundle.ts"],
  "vendor/ns-ingredients",
);

// Fonts (OFL) from @fontsource, latin + latin-ext only: Polish needs latin-ext. Skipped when node_modules is absent.
const FONTS: [string, string, string[]][] = [
  ["bricolage-grotesque", "Bricolage Grotesque", ["600-normal", "800-normal"]],
  ["ibm-plex-sans", "IBM Plex Sans", ["400-normal", "500-normal", "600-normal"]],
  ["ibm-plex-mono", "IBM Plex Mono", ["400-normal", "600-normal"]],
];
const RANGES: Record<string, string> = {
  latin:
    "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
  "latin-ext":
    "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF",
};
const faces: string[] = [];
await Deno.mkdir("public/fonts", { recursive: true });
let copied = 0;
for (const [family, name, weights] of FONTS) {
  for (const w of weights) {
    for (const subset of ["latin", "latin-ext"]) {
      const file = `${family}-${subset}-${w}.woff2`;
      try {
        await Deno.copyFile(`node_modules/@fontsource/${family}/files/${file}`, `public/fonts/${file}`);
        copied++;
        faces.push(
          `@font-face{font-family:"${name}";font-style:normal;font-weight:${
            w.split("-")[0]
          };font-display:swap;src:url(/fonts/${file}) format("woff2");unicode-range:${RANGES[subset]}}`,
        );
      } catch {
        // npm ci not run: the CSS falls back to system fonts.
      }
    }
  }
}
await Deno.writeTextFile("public/fonts/fonts.css", faces.join("\n") + "\n");
console.log(`fonts: ${copied} files`);

// The deployed commit, shown in the footer's source link (AGPL-3.0 §13: users of the site can get its source).
const sha = new TextDecoder().decode(
  (await new Deno.Command("git", { args: ["rev-parse", "HEAD"], stdout: "piped" }).output()).stdout,
).trim();
// Stamped only for the bundle, then put back, so a build never leaves the tree dirty.
const info = "src/build-info.ts";
const kept = await Deno.readTextFile(info);
await Deno.writeTextFile(
  info,
  `// Generated by scripts/build.ts.\nexport const COMMIT = ${JSON.stringify(sha || "unknown")};\n`,
);
try {
  await run(["bundle", "--platform", "browser", "--minify", "-o", "dist/worker.js", "src/worker.ts"]);
} finally {
  await Deno.writeTextFile(info, kept);
}
